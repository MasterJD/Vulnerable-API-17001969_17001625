#!/usr/bin/env node

/**
 * Cyclomatic Complexity Report Generator
 * =======================================
 * Runs ESLint with complexity threshold 0 to discover the complexity
 * of every function in the codebase, then writes a Markdown report.
 *
 * Usage:  node scripts/generate-complexity-report.js
 * Output: CYCLOMATIC_COMPLEXITY_REPORT.md (project root)
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'CYCLOMATIC_COMPLEXITY_REPORT.md');
const THRESHOLD = 10;

// ── Run ESLint ──────────────────────────────────────────────────────────────

let eslintJson;
try {
  const raw = execSync(
    'npx eslint . --rule "complexity: [warn, 0]" -f json',
    { cwd: ROOT, encoding: 'utf-8', stdio: ['pipe', 'pipe', 'pipe'] }
  );
  eslintJson = JSON.parse(raw);
} catch (err) {
  // ESLint exits 1 when there are warnings; stdout still has valid JSON
  if (err.stdout) {
    eslintJson = JSON.parse(err.stdout);
  } else {
    console.error('Failed to run ESLint:', err.message);
    process.exit(1);
  }
}

// ── Parse results ───────────────────────────────────────────────────────────

const entries = []; // { file, line, name, complexity }

for (const fileResult of eslintJson) {
  if (!fileResult.messages || fileResult.messages.length === 0) continue;

  // Build a relative path using forward slashes
  let rel = path.relative(ROOT, fileResult.filePath).replace(/\\/g, '/');

  for (const msg of fileResult.messages) {
    if (msg.ruleId !== 'complexity') continue;

    // Extract complexity number from message like:
    //   "Function 'foo' has a complexity of 3. Maximum allowed is 0."
    //   "Function has a complexity of 1. Maximum allowed is 0."
    const match = msg.message.match(
      /(?:Function '([^']+)' |Function )has a complexity of (\d+)/
    );
    if (!match) continue;

    const name = match[1] || '(anonymous)';
    const complexity = parseInt(match[2], 10);
    entries.push({ file: rel, line: msg.line, name, complexity });
  }
}

// ── Aggregate by file ───────────────────────────────────────────────────────

const byFile = {};
for (const e of entries) {
  if (!byFile[e.file]) byFile[e.file] = [];
  byFile[e.file].push(e);
}

const totalFunctions = entries.length;
const maxComplexity = entries.reduce((m, e) => Math.max(m, e.complexity), 0);
const avgComplexity = totalFunctions
  ? (entries.reduce((s, e) => s + e.complexity, 0) / totalFunctions).toFixed(2)
  : '0.00';

// Distribution buckets
const dist = { low: 0, moderate: 0, high: 0, veryHigh: 0 };
for (const e of entries) {
  if (e.complexity <= 5) dist.low++;
  else if (e.complexity <= 10) dist.moderate++;
  else if (e.complexity <= 20) dist.high++;
  else dist.veryHigh++;
}

const allPass = entries.every(e => e.complexity <= THRESHOLD);

// Top 5 by complexity
const top5 = [...entries].sort((a, b) => b.complexity - a.complexity).slice(0, 5);

// ── Build Markdown ──────────────────────────────────────────────────────────

const now = new Date().toISOString().split('T')[0];
const lines = [];

function ln(s = '') { lines.push(s); }

ln('# Cyclomatic Complexity Report');
ln();
ln(`> **Generated:** ${now}  `);
ln('> **Project:** Vulnerable Node (vulnerable-node-source)  ');
ln('> **Tool:** ESLint — `complexity` rule  ');
ln(`> **Threshold:** Maximum allowed = **${THRESHOLD}**  `);
ln(`> **Result:** ${allPass ? 'All functions PASS (no violations)' : 'VIOLATIONS DETECTED — see details below'}`);
ln();
ln('> *This report is auto-generated by `npm run report:complexity`. Do not edit manually.*');
ln();
ln('---');
ln();
ln('## What is Cyclomatic Complexity?');
ln();
ln('Cyclomatic complexity measures the number of independent execution paths through a function. Each decision point (`if`, `else`, `for`, `while`, `switch/case`, `catch`, `&&`, `||`, `? :`) adds +1 to the base complexity of 1.');
ln();
ln('| Complexity | Risk Level | Interpretation |');
ln('|------------|------------|----------------|');
ln('| 1–5        | Low        | Simple, easy to test and maintain |');
ln('| 6–10       | Moderate   | Acceptable; may benefit from refactoring |');
ln('| 11–20      | High       | Difficult to test; refactoring recommended |');
ln('| 21+        | Very High  | Untestable; must be refactored |');
ln();
ln(`**Configured threshold: ${THRESHOLD}** — Functions exceeding this value will fail the CI build.`);
ln();
ln('---');
ln();
ln('## Summary by File');
ln();
ln('| File | Functions Analyzed | Max Complexity | Status |');
ln('|------|--------------------|----------------|--------|');

const sortedFiles = Object.keys(byFile).sort();
for (const file of sortedFiles) {
  const fns = byFile[file];
  const fMax = fns.reduce((m, e) => Math.max(m, e.complexity), 0);
  const status = fMax <= THRESHOLD ? 'PASS' : 'FAIL';
  ln(`| \`${file}\` | ${fns.length} | ${fMax} | ${status} |`);
}
ln(`| **Total** | **${totalFunctions}** | **${maxComplexity}** | **${allPass ? 'ALL PASS' : 'FAIL'}** |`);
ln();
ln('---');
ln();
ln('## Detailed Function-Level Report');

for (const file of sortedFiles) {
  const fns = byFile[file];
  ln();
  ln(`### \`${file}\``);
  ln();
  ln('| Line | Function | Complexity | Status |');
  ln('|------|----------|------------|--------|');
  for (const e of fns) {
    const status = e.complexity <= THRESHOLD ? 'PASS' : '**FAIL**';
    ln(`| ${e.line} | \`${e.name}\` | ${e.complexity} | ${status} |`);
  }
}

ln();
ln('---');
ln();
ln('## Complexity Distribution');
ln();

// Bar chart
const barMax = 40;
const barScale = totalFunctions > 0 ? barMax / totalFunctions : 0;
function bar(count) {
  const len = Math.max(1, Math.round(count * barScale));
  return count > 0 ? '█'.repeat(len) : ' ';
}

ln('```');
ln(`Complexity 1–5  (Low):       ${bar(dist.low).padEnd(barMax)}  ${dist.low} functions (${(dist.low / totalFunctions * 100).toFixed(1)}%)`);
ln(`Complexity 6–10 (Moderate):  ${bar(dist.moderate).padEnd(barMax)}  ${dist.moderate} functions (${(dist.moderate / totalFunctions * 100).toFixed(1)}%)`);
ln(`Complexity 11–20 (High):     ${bar(dist.high).padEnd(barMax)}  ${dist.high} functions (${(dist.high / totalFunctions * 100).toFixed(1)}%)`);
ln(`Complexity 21+  (Very High): ${bar(dist.veryHigh).padEnd(barMax)}  ${dist.veryHigh} functions (${(dist.veryHigh / totalFunctions * 100).toFixed(1)}%)`);
ln(`                                                          Total: ${totalFunctions} functions`);
ln('```');
ln();
ln('| Range | Count | Percentage | Risk |');
ln('|-------|-------|------------|------|');
ln(`| 1–5 (Low) | ${dist.low} | ${(dist.low / totalFunctions * 100).toFixed(1)}% | Simple, well-structured |`);
ln(`| 6–10 (Moderate) | ${dist.moderate} | ${(dist.moderate / totalFunctions * 100).toFixed(1)}% | Acceptable |`);
ln(`| 11–20 (High) | ${dist.high} | ${(dist.high / totalFunctions * 100).toFixed(1)}% | Refactoring recommended |`);
ln(`| 21+ (Very High) | ${dist.veryHigh} | ${(dist.veryHigh / totalFunctions * 100).toFixed(1)}% | Must refactor |`);
ln();
ln(`**Average complexity:** ${avgComplexity}  `);
ln(`**Maximum complexity:** ${maxComplexity}`);
ln();
ln('---');
ln();
ln('## Highest Complexity Functions (Top 5)');
ln();
ln('| Rank | Function | File | Line | Complexity |');
ln('|------|----------|------|------|------------|');
for (let i = 0; i < top5.length; i++) {
  const e = top5[i];
  ln(`| ${i + 1} | \`${e.name}\` | \`${e.file}\` | ${e.line} | **${e.complexity}** |`);
}

ln();
ln('---');
ln();
ln('## Conclusion');
ln();
if (allPass) {
  ln(`All ${totalFunctions} functions in the codebase are within the configured cyclomatic complexity threshold of **${THRESHOLD}**. The maximum observed complexity is **${maxComplexity}**.`);
  ln();
  ln(`${(dist.low / totalFunctions * 100).toFixed(1)}% of all functions have a complexity of 5 or below, indicating a codebase with predominantly simple, linear control flow that is easy to test and maintain.`);
} else {
  const violations = entries.filter(e => e.complexity > THRESHOLD);
  ln(`**${violations.length} function(s)** exceed the configured cyclomatic complexity threshold of **${THRESHOLD}**. These must be refactored before the build can pass.`);
}

ln();
ln('---');
ln();
ln('*Report auto-generated by `npm run report:complexity` as part of the CI Governance Pipeline.*');
ln('');

// ── Write file ──────────────────────────────────────────────────────────────

fs.writeFileSync(OUTPUT, lines.join('\n'), 'utf-8');
console.log(`✔ Complexity report written to ${path.relative(ROOT, OUTPUT)}`);
console.log(`  ${totalFunctions} functions analyzed | max complexity: ${maxComplexity} | threshold: ${THRESHOLD} | ${allPass ? 'ALL PASS' : 'FAIL'}`);

process.exit(allPass ? 0 : 1);
