#!/usr/bin/env node

/**
 * CI Governance Log Generator
 * ============================
 * Reads Jest coverage-summary.json and ESLint results to produce
 * an up-to-date CI_GOVERNANCE_LOG.md report.
 *
 * Prerequisites: Run `npm test` first so coverage/ exists.
 *
 * Usage:  node scripts/generate-governance-log.js
 * Output: CI_GOVERNANCE_LOG.md (project root)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'CI_GOVERNANCE_LOG.md');
const COVERAGE_FILE = path.join(ROOT, 'coverage', 'coverage-summary.json');
const THRESHOLD = 80;
const COMPLEXITY_MAX = 10;

// ── Read coverage data ─────────────────────────────────────────────────────

if (!fs.existsSync(COVERAGE_FILE)) {
  console.error('ERROR: coverage/coverage-summary.json not found.');
  console.error('Run `npm test` first to generate coverage data.');
  process.exit(1);
}

const coverageData = JSON.parse(fs.readFileSync(COVERAGE_FILE, 'utf-8'));
const total = coverageData.total;

// Per-file coverage
const fileEntries = [];
for (const [filePath, data] of Object.entries(coverageData)) {
  if (filePath === 'total') continue;
  let rel = path.relative(ROOT, filePath).replace(/\\/g, '/');
  fileEntries.push({
    file: rel,
    stmts: data.statements.pct,
    branches: data.branches.pct,
    funcs: data.functions.pct,
    lines: data.lines.pct,
  });
}
fileEntries.sort((a, b) => a.file.localeCompare(b.file));

// Determine pass/fail
const metrics = [
  { name: 'Statements', value: total.statements.pct, total: total.statements.total, covered: total.statements.covered },
  { name: 'Branches', value: total.branches.pct, total: total.branches.total, covered: total.branches.covered },
  { name: 'Functions', value: total.functions.pct, total: total.functions.total, covered: total.functions.covered },
  { name: 'Lines', value: total.lines.pct, total: total.lines.total, covered: total.lines.covered },
];
const allPass = metrics.every(m => m.value >= THRESHOLD);

// ── Read package.json for metadata ──────────────────────────────────────────

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf-8'));
const deps = pkg.dependencies || {};
const devDeps = pkg.devDependencies || {};

// ── Build Markdown ──────────────────────────────────────────────────────────

const now = new Date().toISOString().split('T')[0];
const lines = [];

function ln(s = '') { lines.push(s); }

ln('# CI Governance Pipeline — Log');
ln();
ln(`> **Generated:** ${now}  `);
ln(`> **Project:** ${pkg.name} v${pkg.version}  `);
ln('> **Objective:** Enforce code quality via automated governance gates (coverage + complexity).  ');
ln();
ln('> *This report is auto-generated by `npm run report:governance`. Do not edit manually.*');
ln();
ln('---');
ln();

// ── Section 1: Overview ─────────────────────────────────────────────────────

ln('## 1. Overview');
ln();
ln('This pipeline enforces two governance gates on every commit and pull request:');
ln();
ln('| Gate | Tool | Threshold | Behavior |');
ln('|------|------|-----------|----------|');
ln(`| **Code Complexity** | ESLint | Max cyclomatic complexity = ${COMPLEXITY_MAX} | Build fails if any function exceeds ${COMPLEXITY_MAX} independent code paths |`);
ln(`| **Code Coverage** | Jest | ${THRESHOLD}% minimum (branches, functions, lines, statements) | Build fails if any coverage metric drops below ${THRESHOLD}% |`);
ln();
ln('Both gates run automatically in GitHub Actions and can be run locally with `npm run ci`.');
ln();
ln('---');
ln();

// ── Section 2: Dependencies ────────────────────────────────────────────────

ln('## 2. Dependencies');
ln();
ln('### Production Dependencies');
ln();
ln('| Package | Version |');
ln('|---------|---------|');
for (const [name, version] of Object.entries(deps).sort()) {
  ln(`| \`${name}\` | ${version} |`);
}
ln();
ln('### Dev Dependencies (Governance Tooling)');
ln();
ln('| Package | Version | Purpose |');
ln('|---------|---------|---------|');
const devPurpose = {
  jest: 'Test runner with built-in code coverage (Istanbul/V8)',
  eslint: 'Static analysis — enforces cyclomatic complexity rule',
  supertest: 'HTTP assertion library for integration-testing Express routes',
};
for (const [name, version] of Object.entries(devDeps).sort()) {
  ln(`| \`${name}\` | ${version} | ${devPurpose[name] || '—'} |`);
}
ln();
ln('---');
ln();

// ── Section 3: Scripts ─────────────────────────────────────────────────────

ln('## 3. Package.json Scripts');
ln();
ln('```json');
ln(`"scripts": ${JSON.stringify(pkg.scripts, null, 2)}`);
ln('```');
ln();
ln('| Script | Purpose |');
ln('|--------|---------|');
const scriptDesc = {
  'start': 'Start the application server',
  'test': 'Run Jest with coverage; `--forceExit` ensures exit after async; `--detectOpenHandles` warns about leaks',
  'lint': 'Run ESLint against all source files',
  'ci': 'Run the full governance pipeline locally (lint → test → reports)',
  'report:complexity': 'Auto-generate `CYCLOMATIC_COMPLEXITY_REPORT.md`',
  'report:governance': 'Auto-generate this log (`CI_GOVERNANCE_LOG.md`)',
  'report': 'Generate all governance reports',
};
for (const [name, desc] of Object.entries(scriptDesc)) {
  if (pkg.scripts[name]) {
    ln(`| \`npm run ${name}\` | ${desc} |`);
  }
}
ln();
ln('---');
ln();

// ── Section 4: Coverage Results ─────────────────────────────────────────────

ln('## 4. Code Coverage Results');
ln();
ln('### Global Totals');
ln();
ln('| Metric | Covered | Total | Percentage | Threshold | Status |');
ln('|--------|---------|-------|------------|-----------|--------|');
for (const m of metrics) {
  const status = m.value >= THRESHOLD ? 'PASS' : '**FAIL**';
  ln(`| ${m.name} | ${m.covered} | ${m.total} | ${m.value}% | ${THRESHOLD}% | ${status} |`);
}
ln();

// ── Per-file coverage table ─────────────────────────────────────────────────

ln('### Per-File Breakdown');
ln();
ln('| File | Stmts | Branch | Funcs | Lines |');
ln('|------|-------|--------|-------|-------|');
for (const f of fileEntries) {
  ln(`| \`${f.file}\` | ${f.stmts}% | ${f.branches}% | ${f.funcs}% | ${f.lines}% |`);
}
ln();
ln('### coverage-summary.json');
ln();
ln('```json');
ln(JSON.stringify({
  lines:      { total: total.lines.total,      covered: total.lines.covered,      pct: total.lines.pct },
  statements: { total: total.statements.total,  covered: total.statements.covered,  pct: total.statements.pct },
  functions:  { total: total.functions.total,    covered: total.functions.covered,    pct: total.functions.pct },
  branches:   { total: total.branches.total,     covered: total.branches.covered,     pct: total.branches.pct },
}, null, 2));
ln('```');
ln();
ln('---');
ln();

// ── Section 5: Governance Gates ─────────────────────────────────────────────

ln('## 5. How the Governance Gates Work');
ln();
ln('### Gate 1: Cyclomatic Complexity (ESLint)');
ln();
ln('```');
ln('Developer writes function with 12 decision points');
ln('  → npm run lint');
ln('  → ESLint reports: "Function has a complexity of 12. Maximum allowed is 10."');
ln('  → Exit code 1');
ln('  → CI build FAILS');
ln('  → Developer must refactor to reduce complexity');
ln('```');
ln();
ln('### Gate 2: Coverage Threshold (Jest)');
ln();
ln('```');
ln('Developer adds new code without tests → coverage drops to 75%');
ln('  → npm test');
ln(`  → Jest reports: "Global coverage threshold for lines (${THRESHOLD}%) not met: 75%"`);
ln('  → Exit code 1');
ln('  → CI build FAILS');
ln(`  → Developer must add tests to restore coverage ≥ ${THRESHOLD}%`);
ln('```');
ln();
ln('### Combined Flow in GitHub Actions');
ln();
ln('```');
ln('Push to any branch');
ln('  │');
ln('  ├─ Checkout + Setup Node');
ln('  ├─ npm ci (install from lock file)');
ln('  ├─ npm run lint ───── ESLint complexity check');
ln('  │     └─ FAIL? → Job fails immediately');
ln('  ├─ npm test ──────── Jest with coverage');
ln('  │     └─ FAIL? → Job fails immediately');
ln('  ├─ npm run report ── Generate governance reports');
ln('  └─ Upload artifacts (coverage + reports)');
ln('```');
ln();
ln('---');
ln();

// ── Section 6: Usage ─────────────────────────────────────────────────────────

ln('## 6. Usage Reference');
ln();
ln('```bash');
ln('# Run ESLint only');
ln('npm run lint');
ln();
ln('# Run tests with coverage');
ln('npm test');
ln();
ln('# Run full CI pipeline (lint + test)');
ln('npm run ci');
ln();
ln('# Regenerate governance reports');
ln('npm run report');
ln();
ln('# View HTML coverage report');
ln('start coverage/lcov-report/index.html    # Windows');
ln('open coverage/lcov-report/index.html     # macOS');
ln('xdg-open coverage/lcov-report/index.html # Linux');
ln('```');
ln();
ln('---');
ln();
ln('*Report auto-generated by `npm run report:governance` as part of the CI Governance Pipeline.*');
ln('');

// ── Write file ──────────────────────────────────────────────────────────────

fs.writeFileSync(OUTPUT, lines.join('\n'), 'utf-8');
console.log(`✔ Governance log written to ${path.relative(ROOT, OUTPUT)}`);
console.log(`  Coverage: stmts=${total.statements.pct}% branch=${total.branches.pct}% funcs=${total.functions.pct}% lines=${total.lines.pct}%`);
console.log(`  Threshold: ${THRESHOLD}% | ${allPass ? 'ALL PASS' : 'FAIL'}`);
